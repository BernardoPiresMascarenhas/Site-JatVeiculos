/**
 * Monta as fotos de uma pasta em /public. Cada parte do caminho é codificada
 * por completo (espaços, vírgulas etc.), como o servidor de arquivos espera.
 */
function photoSet(
  folder: string,
  items: { file: string; label: string; alt: string; focus?: string; width?: number; height?: number }[],
): VehicleImage[] {
  return items.map(({ file, label, alt, focus = "50% 55%", width = 1280, height = 854 }) => ({
    src: `/${encodeURIComponent(folder)}/${encodeURIComponent(file)}`,
    width,
    height,
    alt,
    label,
    focus,
    detail: focus,
    credit: "JAT Veículos",
  }));
}

